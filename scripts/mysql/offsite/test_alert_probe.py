        self.assertEqual((status["state"], status["detail"]), ("fail", "app runs on mysql (cached config), expected sqlite"))
        (self.root / "app" / ".env").write_text("DB_CONNECTION=mysql\n")
        on_sqlite = CACHED_CONFIG.replace("'default' => 'mysql',", "'default' => 'sqlite',")
        cached.write_text(on_sqlite)
