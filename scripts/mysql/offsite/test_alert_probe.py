class CutoverFixture(ProbeFixture):
    """The writer hold is installed: nginx holds the site unless the open marker exists."""

    def setUp(self):
        super().setUp()
        self.baseline()  # Before the hold: the money digest reads SQLite.
        self.write_access(100, 1, minutes_ago=20)
        self.boot = BOOT
        self.view_file = self.root / "cutover-view" / "view.json"
        self.view_file.parent.mkdir()
        self.marker = self.root / "repro-cutover-ingress" / "open"
        self.marker.parent.mkdir()
        self.plan["cutover"] = {"view_file": str(self.view_file), "ingress_open": str(self.marker)}
        self.plan["conditions"] = self.plan["conditions"] + ["site_held"]

    def context(self, now=NOW):
        context = super().context(now)
        context.boot_id = lambda: self.boot
        return context

    def journal(self, *steps, started=NOW - 600):
        """A journal written by the real cutover runner; the hold starts at `started`."""
        clock = [started - 60]
        journal = Journal(self.root / "repro-cutover-fence")
        adapter = FixtureAdapter(journal, IDENTITY)
        runner = Runner(journal, IDENTITY, adapter, lambda: clock[0])
        runner.initialize()
        clock[0] = started
        for step in steps:
            if step == "hold":
                runner.perform("hold", runner.approval_request("hold"))
            elif step == "freeze":
                runner.perform("freeze")
            elif step == "abort":
                clock[0] += 60
                runner.perform("abort")
            elif step == "reboot":
                adapter.BOOT_ID = self.boot = REBOOTED
                clock[0] += 60
                runner.perform("tick")
        self.publish(cutover_view.build(journal.path, self.boot, NOW))
        return journal

    def publish(self, record):
        cutover_view.write(self.view_file, record)

    def view(self, **fields):
        """A view of a journal state the SQLite-only fixture runner cannot reach (MySQL phases)."""
        record = {"schema": cutover_view.SCHEMA, "observed_unix_s": NOW, "boot_id": self.boot, "journal": "present",
                  "run_id": IDENTITY.run_id, "phase": "mysql_authoritative", "writes_possible": True,
                  "started_at": NOW - 1200, "pending_action": None, "hold_boot_id": self.boot}
        self.publish(record | fields)

    def hold_ended(self, phase, started):
        """The hold started at `started` and ended in `phase`, but nobody has reopened the site yet."""
        if phase == "sqlite_authoritative":
            self.journal("hold", "abort", started=started)  # The real runner's rollback.
        else:
            self.view(phase=phase, started_at=started)

    def open_site(self, reopened_at=NOW - 300):
        self.marker.write_text(json.dumps({"version": 1, "engine": "sqlite"}))
        os.utime(self.marker, (reopened_at, reopened_at))

    def held_requests(self, minutes_ago=5, total=100):
        """nginx answers every request 503 while the open marker is absent."""
        self.write_access(total, total, minutes_ago=minutes_ago, status=503, append=True)

    def failing(self, now=NOW):
        return {name for name, item in self.run_probe(now).items() if item["state"] != "ok"}


